#!/usr/bin/env node
/**
 * NOT FOR PROFIT — civic public good, not a commercial product.
 *
 * Regenerate Poseidon t=3 artifacts from circuits/vendor/poseidon-bn254-x5-t3.json.
 * Does not run a ceremony. Constants are circomlib bn254 Poseidon(2).
 *
 *   node circuits/scripts/gen-poseidon.mjs
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(SCRIPT_DIR, "../..");
const SRC = path.join(REPO, "circuits/vendor/poseidon-bn254-x5-t3.json");

const spec = JSON.parse(fs.readFileSync(SRC, "utf8"));
const C = spec.C.map((x) => BigInt(x));
const M = spec.M.map((row) => row.map((x) => BigInt(x)));
if (C.length !== 195) throw new Error(`expected 195 round constants, got ${C.length}`);

function dec(n) {
  return n.toString(10);
}

function word(n) {
  return n.toString(16).padStart(64, "0");
}

const header = `// NOT FOR PROFIT — civic public good, not a commercial product.
// Generated by circuits/scripts/gen-poseidon.mjs from circuits/vendor/poseidon-bn254-x5-t3.json.
// HASH_SCHEME: zk-voting.hash.poseidon-bn254-x5-t3-v1
// circomlib-compatible Poseidon(2), bn254, x^5, t=3. Not a Groth16 ceremony.
`;

const circom = `pragma circom 2.0.0;

// NOT FOR PROFIT — civic public good, not a commercial product.
// Generated by circuits/scripts/gen-poseidon.mjs from circuits/vendor/poseidon-bn254-x5-t3.json.
// HASH_SCHEME: zk-voting.hash.poseidon-bn254-x5-t3-v1
// Round constants C and MDS matrix M for t=3 only.
// Source: iden3/circomlib poseidon_constants.json (C[1], M[1]). Not a ceremony.

function POSEIDON_C(t) {
    assert(t == 3);
    var C[195] = [
${C.map((n) => `        ${dec(n)}`).join(",\n")}
    ];
    return C;
}

function POSEIDON_M(t) {
    assert(t == 3);
    var M[3][3] = [
${M.map((row) => `        [${row.map(dec).join(", ")}]`).join(",\n")}
    ];
    return M;
}
`;

const hex = C.map(word).join("");
const mDec = M.map((row) => row.map(dec));

const sol = `// SPDX-License-Identifier: AGPL-3.0-or-later
pragma solidity ^0.8.24;

${header}
/// @title PoseidonT3
/// @notice \`zk-voting.hash.poseidon-bn254-x5-t3-v1\`. Matches circomlib Poseidon(2)
///         and \`packages/proof-helpers/poseidon.js\`. Not a trusted setup.
library PoseidonT3 {
    uint256 internal constant F =
        21888242871839275222246405745257275088548364400416034343698204186575808495617;
    uint256 internal constant N_ROUNDS_F = 8;
    uint256 internal constant N_ROUNDS_P = 57;

    uint256 internal constant M00 = ${mDec[0][0]};
    uint256 internal constant M01 = ${mDec[0][1]};
    uint256 internal constant M02 = ${mDec[0][2]};
    uint256 internal constant M10 = ${mDec[1][0]};
    uint256 internal constant M11 = ${mDec[1][1]};
    uint256 internal constant M12 = ${mDec[1][2]};
    uint256 internal constant M20 = ${mDec[2][0]};
    uint256 internal constant M21 = ${mDec[2][1]};
    uint256 internal constant M22 = ${mDec[2][2]};

    /// @dev 195 round-constant words, 32 bytes each, big-endian.
    bytes internal constant C_DATA =
        hex"${hex}";

    function hashLeftRight(uint256 left, uint256 right) internal pure returns (uint256) {
        uint256[3] memory state;
        state[0] = 0;
        state[1] = left % F;
        state[2] = right % F;
        bytes memory cData = C_DATA;
        uint256 total = N_ROUNDS_F + N_ROUNDS_P;
        for (uint256 r = 0; r < total; r++) {
            state[0] = addmod(state[0], _word(cData, r * 3), F);
            state[1] = addmod(state[1], _word(cData, r * 3 + 1), F);
            state[2] = addmod(state[2], _word(cData, r * 3 + 2), F);
            if (r < N_ROUNDS_F / 2 || r >= N_ROUNDS_F / 2 + N_ROUNDS_P) {
                state[0] = _pow5(state[0]);
                state[1] = _pow5(state[1]);
                state[2] = _pow5(state[2]);
            } else {
                state[0] = _pow5(state[0]);
            }
            state = _mix(state);
        }
        return state[0];
    }

    function _pow5(uint256 x) private pure returns (uint256) {
        uint256 x2 = mulmod(x, x, F);
        uint256 x4 = mulmod(x2, x2, F);
        return mulmod(x4, x, F);
    }

    function _mix(uint256[3] memory s) private pure returns (uint256[3] memory o) {
        o[0] = addmod(addmod(mulmod(M00, s[0], F), mulmod(M01, s[1], F), F), mulmod(M02, s[2], F), F);
        o[1] = addmod(addmod(mulmod(M10, s[0], F), mulmod(M11, s[1], F), F), mulmod(M12, s[2], F), F);
        o[2] = addmod(addmod(mulmod(M20, s[0], F), mulmod(M21, s[1], F), F), mulmod(M22, s[2], F), F);
    }

    function _word(bytes memory data, uint256 i) private pure returns (uint256 v) {
        assembly {
            v := mload(add(add(data, 0x20), mul(i, 0x20)))
        }
    }
}
`;

const browser = `/**
 * NOT FOR PROFIT — civic public good, not a commercial product.
 *
 * Browser Poseidon(2) for zk-voting.hash.poseidon-bn254-x5-t3-v1.
 * Generated by circuits/scripts/gen-poseidon.mjs. Same permutation as
 * packages/proof-helpers/poseidon.js and Solidity PoseidonT3.
 * Not a Groth16 ceremony. The demo passkey commitment is poseidonCommitmentHex.
 */

const F = ${spec.field}n;
const N_ROUNDS_F = ${spec.nRoundsF};
const N_ROUNDS_P = ${spec.nRoundsP};
const C = [
${C.map((n) => `  ${dec(n)}n`).join(",\n")}
];
const M = [
${M.map((row) => `  [${row.map((n) => `${dec(n)}n`).join(", ")}]`).join(",\n")}
];

function pow5(a) {
  const x2 = (a * a) % F;
  const x4 = (x2 * x2) % F;
  return (x4 * a) % F;
}

function mod(n) {
  const x = typeof n === "bigint" ? n : BigInt(n);
  if (x < 0n) throw new Error("poseidon: negative field element");
  return x % F;
}

/** @param {Array<string|number|bigint>} inputs exactly 2 field elements */
export function poseidon(inputs) {
  if (!Array.isArray(inputs) || inputs.length !== 2) {
    throw new Error("poseidon: ZK-Voting Poseidon(2) expects exactly 2 inputs");
  }
  const state = [0n, mod(inputs[0]), mod(inputs[1])];
  const total = N_ROUNDS_F + N_ROUNDS_P;
  for (let r = 0; r < total; r += 1) {
    for (let i = 0; i < 3; i += 1) state[i] = (state[i] + C[r * 3 + i]) % F;
    if (r < N_ROUNDS_F / 2 || r >= N_ROUNDS_F / 2 + N_ROUNDS_P) {
      for (let i = 0; i < 3; i += 1) state[i] = pow5(state[i]);
    } else {
      state[0] = pow5(state[0]);
    }
    const next = [0n, 0n, 0n];
    for (let i = 0; i < 3; i += 1) {
      let acc = 0n;
      for (let j = 0; j < 3; j += 1) acc = (acc + M[i][j] * state[j]) % F;
      next[i] = acc;
    }
    state[0] = next[0];
    state[1] = next[1];
    state[2] = next[2];
  }
  return state[0];
}

/** HashLeftRight. Matches circuits/hasher/poseidon.circom Hasher(). */
export function poseidonHashLeftRight(left, right) {
  return poseidon([left, right]);
}

/** 0x-prefixed 32-byte hex of Poseidon(trapdoor, nullifierSecret). */
export function poseidonCommitmentHex(trapdoor, nullifierSecret) {
  const n = poseidonHashLeftRight(trapdoor, nullifierSecret);
  return "0x" + n.toString(16).padStart(64, "0");
}

export const POSEIDON_HASH_SCHEME = "zk-voting.hash.poseidon-bn254-x5-t3-v1";
`;

const pkgJson = path.join(REPO, "packages/proof-helpers/poseidon-constants.json");
fs.writeFileSync(pkgJson, JSON.stringify(spec) + "\n");
fs.writeFileSync(path.join(REPO, "circuits/hasher/poseidon_constants_t3.circom"), circom);
fs.writeFileSync(path.join(REPO, "smart-contracts/src/hasher/PoseidonT3.sol"), sol);
fs.writeFileSync(path.join(REPO, "apps/node/public/poseidon.js"), browser);
console.log("generated poseidon circom constants, PoseidonT3.sol, public/poseidon.js");
